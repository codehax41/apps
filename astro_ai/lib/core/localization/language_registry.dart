  static LanguageOption getById(String id) {
    return supportedLanguages.firstWhere(
      (lang) => lang.id.toLowerCase() == id.toLowerCase(),
      orElse: () => defaultLanguage,
    );
  }

  static LanguageOption getByLocale(String locale) {
    return supportedLanguages.firstWhere(
      (lang) => lang.locale.toLowerCase() == locale.toLowerCase() ||
                lang.id.toLowerCase() == locale.split('-').first.toLowerCase(),
      orElse: () => defaultLanguage,
    );
  }

  static List<LanguageOption> getIndianLanguages() {
    return supportedLanguages.where((l) => l.supportsIndianVoice).toList();
  }
